static uint8_t matrix_green[24];
static uint8_t matrix_red[24];

void LEDMatrix_Init(void) {
    LEDMatrix_Clear();
}

void LEDMatrix_Clear(void) {
    for (uint8_t i = 0; i < 24; i++) {
        matrix_green[i] = 0;
        matrix_red[i] = 0;
    }
}

void LEDMatrix_Print(const char* str, uint8_t color) {
    uint8_t col = 0;
    LEDMatrix_Clear();
    
    while (*str && col < 24) {
        char c = *str++;
        uint8_t idx = 36;
        
        if (c >= '0' && c <= '9') idx = c - '0';
        else if (c >= 'A' && c <= 'Z') idx = c - 'A' + 10;
        else if (c >= 'a' && c <= 'z') idx = c - 'a' + 10;
        else if (c == '-') idx = 37;
        else if (c == ' ') { col += 4; continue; }
        
        for (uint8_t i = 0; i < 5 && col < 24; i++) {
            if (color & 1) matrix_red[col] = font5x7[idx][i];
            if (color & 2) matrix_green[col] = font5x7[idx][i];
            col++;
        }
        col++;
    }
}

static uint8_t extract_row(uint8_t* buf, uint8_t start_col, uint8_t row) {
    uint8_t res = 0;
    for (uint8_t i = 0; i < 8; i++) {
        if (buf[start_col + i] & (1 << (7 - row))) {
            res |= (uint8_t)(1 << (7 - i));
        }
    }
    return res;
}

void LEDMatrix_Scan(void) {
    static uint8_t row = 0;
    uint8_t out[8];
    
    out[7] = extract_row(matrix_green, 0, row);
    out[6] = extract_row(matrix_red, 0, row);
    out[5] = extract_row(matrix_green, 8, row);
    out[4] = extract_row(matrix_red, 8, row);
    out[3] = extract_row(matrix_green, 16, row);
    out[2] = extract_row(matrix_red, 16, row);
    out[1] = 0;
    out[0] = (uint8_t)(1 << row);

    MBI_WriteData(out, 8, MBI_LE2_MATRIX);
    row = (row + 1) & 7;
}
